// Helper Functions
export const getCatalogBrands = (vehicleType?: VehicleType): string[] => {
  const filtered = vehicleType
    ? PHILIPPINE_VEHICLE_CATALOG.filter(v => v.vehicle_type === vehicleType)
    : PHILIPPINE_VEHICLE_CATALOG;
  return Array.from(new Set(filtered.map(v => v.brand))).sort();
};

export const getCatalogModels = (brand: string, vehicleType?: VehicleType): string[] => {
  const filtered = PHILIPPINE_VEHICLE_CATALOG.filter(v => {
    const matchBrand = v.brand.toLowerCase() === brand.toLowerCase();
    const matchType = vehicleType ? v.vehicle_type === vehicleType : true;
    return matchBrand && matchType;
  });
  return Array.from(new Set(filtered.map(v => v.model))).sort();
};

export const getCatalogVersions = (brand: string, model: string, vehicleType?: VehicleType): VehicleCatalogItem[] => {
  return PHILIPPINE_VEHICLE_CATALOG.filter(v => {
    const matchBrand = v.brand.toLowerCase() === brand.toLowerCase();
    const matchModel = v.model.toLowerCase() === model.toLowerCase();
    const matchType = vehicleType ? v.vehicle_type === vehicleType : true;
    return matchBrand && matchModel && matchType;
  });
};

export const findCatalogItem = (
  brand: string,
  model: string,
  version?: string
): VehicleCatalogItem | undefined => {
  const brandTrimmed = brand.trim().toLowerCase();
  const modelTrimmed = model.trim().toLowerCase();

  if (version) {
    const versionTrimmed = version.trim().toLowerCase();
    const exact = PHILIPPINE_VEHICLE_CATALOG.find(
      v =>
        v.brand.toLowerCase() === brandTrimmed &&
        v.model.toLowerCase() === modelTrimmed &&
        v.version.toLowerCase() === versionTrimmed
    );
    if (exact) return exact;
  }

  // Fallback to match brand & model
  return PHILIPPINE_VEHICLE_CATALOG.find(
    v =>
      v.brand.toLowerCase() === brandTrimmed &&
      (v.model.toLowerCase() === modelTrimmed || modelTrimmed.includes(v.model.toLowerCase()))
  );
};

export const calculateTripFuelCost = (
  distanceKm: number,
  efficiencyKmPerL: number,
  pricePerLiter: number
): { liters: number; cost: number } => {
  const safeEfficiency = Math.max(1, efficiencyKmPerL || 40);
  const safeDistance = Math.max(0, distanceKm || 0);
  const liters = Number((safeDistance / safeEfficiency).toFixed(2));
  const cost = Math.round(liters * pricePerLiter);
  return { liters, cost };
};
